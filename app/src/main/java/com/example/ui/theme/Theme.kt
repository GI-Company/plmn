    primary = CyberCyanMuted,
    onPrimary = LightSurface,
    primaryContainer = LightSurfaceVariant,
    onPrimaryContainer = LightTextPrimary,
    secondary = ShieldEmeraldMuted,
    onSecondary = LightSurface,
